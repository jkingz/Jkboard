import { sql } from "drizzle-orm"
import {
  date,
  index,
  integer,
  pgEnum,
  pgSequence,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core"

import { member } from "./members"
import { project } from "./projects"

export const taskStatusEnum = pgEnum("task_status", [
  "todo",
  "in-progress",
  "in-review",
  "completed",
])

export const taskPriorityEnum = pgEnum("task_priority", [
  "urgent",
  "high",
  "medium",
  "low",
])

/**
 * Backs `task.reference`. Declared here, not created by hand, so a generated
 * migration emits the `CREATE SEQUENCE` the column default depends on.
 */
export const taskReferenceSeq = pgSequence("task_reference_seq")

export const task = pgTable(
  "task",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    /**
     * Short human-facing key shown in the UI, e.g. "TSK-0042".
     * `id` stays a UUID — it is the real key used by every foreign key and
     * route; this column exists purely so people are not reading 36-character
     * UUIDs. Generated by the database, never supplied by the client.
     */
    reference: text("reference")
      .notNull()
      .default(sql`'TSK-' || lpad(nextval('task_reference_seq')::text, 4, '0')`),
    projectId: uuid("project_id")
      .notNull()
      .references(() => project.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    description: text("description").notNull().default(""),
    status: taskStatusEnum("status").notNull().default("todo"),
    priority: taskPriorityEnum("priority").notNull().default("medium"),
    /** One assignee per task. Set to NULL when the assignee leaves. */
    assigneeId: uuid("assignee_id").references(() => member.id, {
      onDelete: "set null",
    }),
    dueDate: date("due_date", { mode: "string" }).notNull(),
    /** Ordering within a kanban column. */
    position: integer("position").notNull().default(0),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true })
      .defaultNow()
      .notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .defaultNow()
      .$onUpdate(() => new Date())
      .notNull(),
  },
  (table) => [
    // Tasks are always fetched as "all tasks in this project".
    index("task_projectId_idx").on(table.projectId),
    // Tasks page filters by status; the calendar walks due dates.
    index("task_status_idx").on(table.status),
    index("task_dueDate_idx").on(table.dueDate),
    index("task_assigneeId_idx").on(table.assigneeId),
    index("task_projectId_status_idx").on(table.projectId, table.status),
    uniqueIndex("task_reference_uidx").on(table.reference),
  ]
)

export type Task = typeof task.$inferSelect
export type NewTask = typeof task.$inferInsert